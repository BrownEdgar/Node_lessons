// =====================================================
// КОНФИГУРАЦИЯ KAFKA
// =====================================================
// Здесь мы создаём главный объект KafkaJS — это точка входа
// для работы с Kafka. Один экземпляр kafka используется
// во всём приложении (singleton-паттерн).
// =====================================================

const { Kafka } = require('kafkajs');

// Kafka — это распределённая система обмена сообщениями.
// Чтобы подключиться, нам нужен адрес хотя бы одного брокера (broker).
// Брокер — это сервер Kafka, который хранит и раздаёт сообщения.
const kafka = new Kafka({
  // clientId — уникальное имя нашего приложения.
  // Kafka использует его для логирования и мониторинга.
  clientId: 'kafka-demo-app',

  // brokers — список адресов брокеров Kafka.
  // В production может быть несколько брокеров для отказоустойчивости.
  brokers: [process.env.KAFKA_BROKER || 'localhost:9092'],
});

module.exports = kafka;
