// =====================================================
// KAFKA CONSUMER — Читатель сообщений
// =====================================================
// Consumer — это компонент, который ЧИТАЕТ сообщения из Kafka.
// Он работает в фоне постоянно, как слушатель.
// Как только в topic появляется новое сообщение —
// consumer его забирает и обрабатывает.
// =====================================================

const kafka = require('../config/kafka');
const Message = require('../models/Message');

// =====================================================
// ЧТО ТАКОЕ CONSUMER GROUP?
// =====================================================
// groupId — идентификатор группы потребителей.
// Если несколько consumer'ов имеют один groupId —
// они объединяются в группу и ДЕЛЯТ сообщения между собой.
//
// Пример с 3 partition и 3 consumer'ами в группе:
//   consumer-1 читает partition-0
//   consumer-2 читает partition-1
//   consumer-3 читает partition-2
//   → Параллельная обработка, каждый читает своё
//
// Если groupId разные — каждый consumer читает ВСЕ сообщения.
// =====================================================
const consumer = kafka.consumer({
  groupId: process.env.KAFKA_GROUP_ID || 'messages-group',
});

// =====================================================
// НАСТРОЙКИ DELIVERY SEMANTICS
// =====================================================
// Это один из самых важных концептов в Kafka.
// "Семантика доставки" отвечает на вопрос:
// "Сколько раз сообщение будет обработано?"
//
// 1. AT-MOST-ONCE (максимум один раз)
//    - autoCommit: true с коротким интервалом
//    - Offset фиксируется ДО обработки сообщения
//    - Риск: если consumer упал ПОСЛЕ коммита offset,
//      но ДО обработки — сообщение будет потеряно
//    - Когда использовать: когда потеря допустима (метрики, логи)
//
// 2. AT-LEAST-ONCE (минимум один раз) ← используем здесь
//    - autoCommit: false, фиксируем ПОСЛЕ обработки
//    - Риск: если consumer упал ПОСЛЕ обработки,
//      но ДО коммита offset — сообщение обработается снова (дубликат)
//    - Когда использовать: важна каждая запись, дубликаты терпимы
//
// 3. EXACTLY-ONCE (ровно один раз)
//    - Самая сложная настройка
//    - Требует транзакций на стороне producer + consumer
//    - Producer: { transactionalId: 'my-app', idempotent: true }
//    - Consumer: isolation.level = 'read_committed'
//    - Когда использовать: финансовые транзакции, критические данные
// =====================================================

// =====================================================
// ЗАПУСК CONSUMER'А
// =====================================================
const startConsumer = async () => {
  try {
    // Подключаемся к Kafka-брокеру
    await consumer.connect();
    console.log('✅ Kafka Consumer подключён');

    // Подписываемся на topic.
    // fromBeginning: true — читать ВСЕ сообщения с самого начала.
    // fromBeginning: false — читать только новые сообщения.
    await consumer.subscribe({
      topic: process.env.KAFKA_TOPIC || 'messages',
      fromBeginning: true, // Читаем всё, включая старые сообщения
    });

    console.log(`📨 Consumer подписан на topic: ${process.env.KAFKA_TOPIC || 'messages'}`);

    // -----------------------------------------------
    // ОСНОВНОЙ ЦИКЛ ЧТЕНИЯ СООБЩЕНИЙ
    // -----------------------------------------------
    // eachMessage вызывается для каждого нового сообщения
    // -----------------------------------------------
    await consumer.run({
      // -----------------------------------------------
      // AT-LEAST-ONCE: autoCommit: false
      // Мы сами управляем фиксацией offset
      // -----------------------------------------------
      autoCommit: false,

      eachMessage: async ({ topic, partition, message }) => {
        // -----------------------------------------------
        // ЧТО ТАКОЕ PARTITION?
        // -----------------------------------------------
        // Partition — это "секция" внутри topic.
        // Topic разбит на несколько partition для параллельности.
        //
        // Представь topic как журнал, разбитый на тома.
        // Каждый том — это partition.
        // Внутри каждого тома сообщения идут строго по порядку.
        //
        // Зачем нужны partition:
        //   1. Масштабируемость: разные partition на разных серверах
        //   2. Параллельность: несколько consumer'ов читают одновременно
        //   3. Порядок: внутри одного partition порядок ГАРАНТИРОВАН
        // -----------------------------------------------

        // -----------------------------------------------
        // ЧТО ТАКОЕ OFFSET?
        // -----------------------------------------------
        // Offset — порядковый номер сообщения в partition.
        // Каждое сообщение получает уникальный offset.
        // Consumer запоминает, до какого offset дочитал.
        // При перезапуске — продолжает с последнего offset.
        //
        // Пример:
        //   partition-0: [msg0, msg1, msg2, msg3, ...]
        //                  ↑     ↑     ↑     ↑
        //   offset:        0     1     2     3
        // -----------------------------------------------

        const key = message.key ? message.key.toString() : 'no-key';
        const value = message.value ? message.value.toString() : '';
        const offset = message.offset;

        console.log('\n📥 Получено новое сообщение:');
        console.log(`   topic:     ${topic}`);
        console.log(`   partition: ${partition}`);  // Важно: из какого partition
        console.log(`   offset:    ${offset}`);      // Важно: какой порядковый номер
        console.log(`   key:       ${key}`);
        console.log(`   value:     ${value}`);

        // -----------------------------------------------
        // СОХРАНЯЕМ СООБЩЕНИЕ В MONGODB
        // -----------------------------------------------
        try {
          const savedMessage = await Message.create({
            content: value,
            key: key,
            partition: partition,
            offset: offset,
          });

          console.log(`✅ Сообщение сохранено в MongoDB, id: ${savedMessage._id}`);

          // -----------------------------------------------
          // AT-LEAST-ONCE: Фиксируем offset ПОСЛЕ сохранения
          // -----------------------------------------------
          // Если бы фиксировали ДО сохранения (at-most-once):
          // при падении после коммита сообщение было бы потеряно.
          // Фиксируем ПОСЛЕ — при падении до коммита:
          // сообщение обработается снова (возможен дубликат).
          // -----------------------------------------------
          await consumer.commitOffsets([
            {
              topic,
              partition,
              offset: String(BigInt(offset) + 1n), // Следующий offset
            },
          ]);

        } catch (dbError) {
          console.error('❌ Ошибка сохранения в MongoDB:', dbError.message);
          // Не фиксируем offset — сообщение будет перечитано (at-least-once)
        }
      },
    });

  } catch (err) {
    console.error('❌ Ошибка Kafka Consumer:', err.message);
    setTimeout(startConsumer, 5000); // Пробуем переподключиться через 5 сек
  }
};

// =====================================================
// ОТКЛЮЧЕНИЕ CONSUMER'А
// =====================================================
const disconnectConsumer = async () => {
  await consumer.disconnect();
  console.log('🔌 Kafka Consumer отключён');
};

module.exports = { startConsumer, disconnectConsumer };
